import fields from '../../../app/i18n/unit_fields.json' with { type: 'json' }

export const SQM_PER_SQFT = 0.09290304
const dimensions = new Map(Object.entries(fields).flatMap(([kind, keys]) => keys.map(key => [key, kind])))
const rawFields = new Set(['notes', 'metadata', 'raw_payload', 'source_payload', 'client_state', 'mapping', 'formula'])

export function areaLabel(value, unit = 'm2') {
  if (typeof value !== 'string' || unit !== 'ft2') return value
  return value.replaceAll('平方米', '平方英尺').replaceAll('㎡', 'ft²').replaceAll('m²', 'ft²').replaceAll('sqm', 'sqft')
}

function unitDimension(unit) {
  if (/^(?:CNY|RMB|元)\/(?:sqm|㎡|m²)/i.test(unit)) return 'price'
  if (/^(?:sqm|㎡|m²)$/.test(unit)) return 'area'
  if (/^(?:CNY|RMB|元|万元|亿元|CNY_10K)$/i.test(unit)) return 'money'
  return ''
}

function dimension(key, parent) {
  if (dimensions.has(key)) return dimensions.get(key)
  if (/(?:_yuan|_fen|_amount|_balance)$/.test(key)) return 'money'
  if (/(?:_area|_area_sqm)$/.test(key)) return 'area'
  if (key === 'adjustment_value') return parent.adjustment_type === 'percent' ? '' : 'money'
  if (key === 'delta' && ('baseline_value' in parent || 'baseline_total' in parent)) return 'money'
  if (key === 'total' && !('rows' in parent) && !('items' in parent) && ('property_fee' in parent || ('rent' in parent && 'month' in parent))) return 'money'
  if (key === 'total' && 'leased' in parent) return 'area'
  if (key === 'leased' && 'total' in parent) return 'area'
  if (key === 'value' || key === 'raw_value') return unitDimension(parent.unit || '') || dimensions.get(parent.key) || ''
  if (key === 'numerator' || key === 'denominator') {
    const code = parent.code || parent.metric_code || ''
    if (code === 'occupancy.area_rate' || code === 'expiry.area_pressure_90d') return 'area'
    if (code === 'collection.rate_month') return 'money'
    if (code === 'rent.effective_daily') return key === 'numerator' ? 'money' : 'area'
    if (key === 'numerator') return unitDimension(parent.unit || '')
  }
  return ''
}

/** Convert a fresh API snapshot, never persisted state or arbitrary user text.
 * Writes use only the fixed area conversion; FX views are read-only.
 */
export function convertUnitPayload(payload, { area = 'm2', rate = 1, direction = 'view' } = {}) {
  const a = area === 'ft2' ? 1 / SQM_PER_SQFT : 1
  const factors = direction === 'input' ? { area: 1 / a, price: a, money: 1 } : { area: a, price: rate / a, money: rate }
  function convert(value, key = '', parent = {}) {
    if (rawFields.has(key)) return value
    const kind = dimension(key, parent)
    const factor = factors[kind] || 1
    if (typeof value === 'number') return direction === 'input' && factor !== 1 ? Number((value * factor).toPrecision(15)) : value * factor
    if (Array.isArray(value)) return value.map(item => convert(item, key, parent))
    if (value && typeof value === 'object') {
      if (key === 'current_by_segment' || key === 'trend_by_segment') {
        const scale = item => typeof item === 'number' ? item * factors.price : Array.isArray(item) ? item.map(scale) : item && typeof item === 'object' ? Object.fromEntries(Object.entries(item).map(([k, v]) => [k, scale(v)])) : item
        return scale(value)
      }
      const result = {}
      for (const [child, item] of Object.entries(value)) result[child] = convert(item, child, value)
      // Dashboard cards include a preformatted copy alongside the raw measure.
      if ('raw_value' in value && typeof value.value === 'string' && result.raw_value != null) {
        result.value = Number(result.raw_value).toLocaleString('en-US', { maximumFractionDigits: 2 })
      }
      return result
    }
    if (kind && typeof value === 'string' && /^-?\d+(?:\.\d+)?$/.test(value)) return Number(value) * factor
    // These two helper texts are generated by the server, not user-entered notes.
    if (direction === 'view' && key === 'helper' && 'raw_value' in parent && typeof value === 'string') {
      return value.replace(/(-?[\d,]+(?:\.\d+)?)\s*(㎡|元)/g, (_, number, unit) => {
        const converted = Number(number.replaceAll(',', '')) * (unit === '㎡' ? a : rate)
        return `${converted.toLocaleString('en-US', { maximumFractionDigits: 2 })} ${unit}`
      })
    }
    return value
  }
  return convert(payload)
}

export function canonicalAreaQuery(path, area) {
  if (area !== 'ft2') return path
  const parsed = new URL(path, 'http://localhost')
  for (const key of ['min_area', 'max_area']) {
    if (parsed.searchParams.has(key)) parsed.searchParams.set(key, String(Number(parsed.searchParams.get(key)) * SQM_PER_SQFT))
  }
  return parsed.pathname + parsed.search + parsed.hash
}
